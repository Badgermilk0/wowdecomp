    "    if (gxTone.y > 1.5) {\n"
    "        c = GxAces(c);\n"
    "    } else if (gxTone.y > 0.5) {\n"
    "        c = GxNeutral(c);\n"
    "    } else {\n"
    "        c = saturate(c);\n"
    "    }\n"
    "\n"
    "    return float4(GxEnc(c), s.a);\n"
    "}\n"
    "\n"
    "// the clusters: the lights whose sphere touches each cell of the view, the count first\n"
    "struct GxLight {\n"
    "    float3 pos;\n"
    "    float radius;\n"
    "    float3 color;\n"
    "    float start;\n"
    "    float flicker;\n"
    "    float seed;\n"
    "    float specular;\n"
    "    float pad;\n"
    "};\n"
    "\n"
    "StructuredBuffer<GxLight> gxLightsIn : register(t0);\n"
    "RWStructuredBuffer<uint> gxClustersOut : register(u0);\n"
    "\n"
    "// the view-space point at clip w 1 seen at ndc\n"
    "float3 GxRay(float2 ndc) {\n"
    "    float4 h = mul(float4(ndc, 0.5, 1.0), gxInvProj);\n"
    "    float3 p = h.xyz / h.w;\n"
    "    return p / max(GxClipW(p), 0.000001);\n"
    "}\n"
    "\n"
    "[numthreads(64, 1, 1)]\n"
    "void ClusterCs(uint3 id : SV_DispatchThreadID) {\n"
    "    uint dx = (uint)gxClusterDims.x;\n"
    "    uint dy = (uint)gxClusterDims.y;\n"
    "    uint dz = (uint)gxClusterDims.z;\n"
    "\n"
    "    if (id.x >= dx * dy * dz) {\n"
    "        return;\n"
    "    }\n"
    "\n"
    "    uint cx = id.x % dx;\n"
    "    uint cy = (id.x / dx) % dy;\n"
    "    uint cz = id.x / (dx * dy);\n"
    "    float x0 = (float)cx / dx * 2.0 - 1.0;\n"
    "    float x1 = (float)(cx + 1) / dx * 2.0 - 1.0;\n"
    "    float y1 = 1.0 - (float)cy / dy * 2.0;\n"
    "    float y0 = 1.0 - (float)(cy + 1) / dy * 2.0;\n"
    "    float w0 = cz == 0 ? 0.0 : exp2((cz - gxClusterZ.y) / gxClusterZ.x);\n"
    "    float w1 = cz + 1 >= dz ? 100000.0 : exp2((cz + 1 - gxClusterZ.y) / gxClusterZ.x);\n"
    "    float3 corners[4] = { GxRay(float2(x0, y0)), GxRay(float2(x1, y0)), GxRay(float2(x0, y1)), GxRay(float2(x1, y1)) };\n"
    "    float3 lo = 1e30;\n"
    "    float3 hi = -1e30;\n"
    "\n"
    "    [unroll] for (uint k = 0; k < 4; k++) {\n"
    "        lo = min(lo, min(corners[k] * w0, corners[k] * w1));\n"
    "        hi = max(hi, max(corners[k] * w0, corners[k] * w1));\n"
    "    }\n"
    "\n"
    "    uint base = id.x * 64u;\n"
    "    uint n = 0;\n"
    "    uint lights = (uint)gxClusterDims.w;\n"
    "\n"
    "    for (uint l = 0; l < lights && n < 63u; l++) {\n"
    "        GxLight light = gxLightsIn[l];\n"
    "        float3 d = clamp(light.pos, lo, hi) - light.pos;\n"
    "\n"
    "        if (dot(d, d) <= light.radius * light.radius) {\n"
    "            gxClustersOut[base + 1u + n] = l;\n"
    "            n++;\n"
    "        }\n"
    "    }\n"
    "\n"
    "    gxClustersOut[base] = n;\n"
    "}\n";

struct ShaderDesc {
    const char* m_entry;
    const char* m_profile;
    bool m_msaa;
};

const ShaderDesc s_shaderDescs[] = {
    { "FullscreenVs", "vs_5_0", false },
    { "AoPs", "ps_5_0", false },
    { "AoPs", "ps_5_0", true },
    { "BlurPs", "ps_5_0", false },
    { "AoCompositePs", "ps_5_0", false },
    { "AoCompositePs", "ps_5_0", true },
    { "FogPs", "ps_5_0", false },
    { "FogPs", "ps_5_0", true },
    { "BloomPrefilterPs", "ps_5_0", false },
    { "BloomDownPs", "ps_5_0", false },
    { "BloomUpPs", "ps_5_0", false },
    { "TonemapPs", "ps_5_0", false },
    { "ClusterCs", "cs_5_0", false },
};

void CopyMatrix(float* out, const C44Matrix& m) {
    memcpy(out, &m, sizeof(float) * 16);
}

// row vector times matrix, as the engine's C3Vector * C44Matrix
void TransformPoint(const float* m, const C3Vector& p, float* out) {
    out[0] = p.x * m[0] + p.y * m[4] + p.z * m[8] + m[12];
    out[1] = p.x * m[1] + p.y * m[5] + p.z * m[9] + m[13];
    out[2] = p.x * m[2] + p.y * m[6] + p.z * m[10] + m[14];
}

void TransformDirection(const float* m, const C3Vector& d, float* out) {
    out[0] = d.x * m[0] + d.y * m[4] + d.z * m[8];
    out[1] = d.x * m[1] + d.y * m[5] + d.z * m[9];
    out[2] = d.x * m[2] + d.y * m[6] + d.z * m[10];
}

float Luminance(const C3Vector& c) {
    return c.x * 0.2126f + c.y * 0.7152f + c.z * 0.0722f;
}

// a colour scaled to luminance 1 (a tint), white when it is too dark to say
void Tint(const C3Vector& c, float* out) {
    float lum = Luminance(c);

    if (lum < 0.02f) {
        out[0] = out[1] = out[2] = 1.0f;
        return;
    }

    out[0] = fminf(c.x / lum, 3.0f);
    out[1] = fminf(c.y / lum, 3.0f);
    out[2] = fminf(c.z / lum, 3.0f);
}

